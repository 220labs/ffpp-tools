#!/usr/bin/env python3
"""The spotting sheet: every block, cut, card, named hit point and spoken line of a cut, by timecode.

Usage:
  bin/tool spotting edl/<cut-id>.edl.tsv [SPEECH.wav] [--out audio/spotting-<ver>.tsv] [--config audio/mix.yaml]

Written by script so a recut regenerates it; nobody copies timecodes by hand.
Timeline positions come from the edit list exactly as edl_cut lays it out (each segment is
round((out-in)/speed*24) frames). Named hit points are the production's: `hits:` in --config
(default audio/mix.yaml in the text root), each [name, clip file name, time in that clip in s],
measured on the clip, not the cut, so they follow the shot wherever the cut puts it.
Spoken lines come
from the speech stem of the cut's production sound (BandIt Plus), when one is given.

Columns: kind, tc_in, tc_out, frame_in, frame_out, sec_in, sec_out, block, source, src_in, note
  kind : block | cut | card | title | black | hit | line
  line : note = peak dBFS of the speech stem inside the line, and the clip whose sound it is
The EDL, the config and --out resolve against the text root (the sheet is text); the speech stem
against the media root. Needs numpy and soundfile only for lines.
Ported from START's spotting.py (2026-09-23): HITS
became the config; the same sheet, bar the header's "Generated by" line.
"""
import sys, os, math, tempfile
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.realpath(__file__))), 'cut'))
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.realpath(__file__))))
import edl_cut  # noqa: E402
from edl_cut import rows, first_frame, snap, tc  # noqa: E402
from lib import cli, production  # noqa: E402

HITS = []   # [(name, clip file name, time in that clip in s)] — from --config
FPS = 24

def segments(edl):
    """Yield dicts per timeline segment, with the top-level block each belongs to."""
    f0 = 0
    for line in open(edl_cut.edl_path(edl)):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        f = line.rstrip('\n').split('\t')
        block = f[4] if len(f) > 4 else os.path.basename(f[0])
        # one row at a time through edl_cut.rows, from a temp file outside the repo (the original wrote
        # .spot-row.tsv into edl/ itself)
        fd, tmp = tempfile.mkstemp(suffix='.spot-row.tsv')
        with os.fdopen(fd, 'w') as fh:
            fh.write(line)
        try:
            for src, a, b, audio, ex in rows(tmp):
                sp = ex[2] if len(ex) > 2 else 1.0
                n = int(round((b - a) / sp * FPS))
                yield dict(f0=f0, n=n, block=block, src=src, a=a, b=b, sp=sp, audio=audio, card=ex[0])
                f0 += n
        finally:
            os.remove(tmp)

def audio_source(s, t):
    """(clip, source time) of the sound heard at timeline second t inside segment s."""
    off = (t - s['f0'] / FPS) * s['sp']
    # exactly where edl_cut.py seeks the sound: snap(in) for the clip's own, the in rounded to 1 ms for from:
    if s['audio'].startswith('from:'):
        clip, at = s['audio'][5:].rsplit('@', 1)
        return os.path.basename(clip), round(float(at), 3) + off
    if s['src'] in ('BLACK', 'CARD'):
        return '', 0.0
    return os.path.basename(s['src']), snap(s['a']) + off

def detect_lines(wav, on_db=-38.0, off_db=-46.0, gap=0.25, min_len=0.12, hop=0.01):
    try:
        import numpy as np, soundfile as sf
    except ImportError:
        sys.exit('spotting: spoken lines need numpy and soundfile: pip3 install --user numpy soundfile')
    x, sr = sf.read(wav, always_2d=True)
    x = x.mean(axis=1)
    h = int(sr * hop); n = len(x) // h
    rms = np.sqrt((x[:n * h].reshape(n, h) ** 2).mean(axis=1) + 1e-12)
    db = 20 * np.log10(rms)
    out, on, start = [], False, 0
    for i, d in enumerate(db):
        if not on and d > on_db:
            on, start = True, i
        elif on and d < off_db:
            on = False; out.append([start, i])
    if on: out.append([start, n])
    merged = []
    for s, e in out:
        if merged and (s - merged[-1][1]) * hop < gap:
            merged[-1][1] = e
        else:
            merged.append([s, e])
    res = []
    for s, e in merged:
        if (e - s) * hop >= min_len:
            res.append((s * hop, e * hop, float(db[s:e].max())))
    return res

def main():
    global HITS
    ns, a = cli.split_roots(sys.argv[1:])
    if not a or a[0].startswith('-'):
        print(__doc__.strip())
        return 0 if a and a[0] in ('-h', '--help') else 2
    R = cli.roots(ns)
    R.say('spotting')
    edl_cut.TEXT = R.text
    os.chdir(R.media)              # clip paths inside the EDL are media-relative, as in edl_cut
    edl = a[0]
    speech = R.m(a[1]) if len(a) > 1 and not a[1].startswith('--') else None
    cut_id = os.path.basename(edl).replace('.edl.tsv', '')
    out = R.t(a[a.index('--out') + 1] if '--out' in a else f'audio/spotting-{cut_id}.tsv')
    cfg = R.t(a[a.index('--config') + 1] if '--config' in a else os.path.join('audio', 'mix.yaml'))
    if os.path.isfile(cfg):
        HITS = [tuple(h) for h in ((production.load_yaml(cfg) or {}).get('hits') or [])]
    else:
        print(f'spotting: no {cfg}: no named hit points', file=sys.stderr)
    segs = list(segments(edl))
    total = segs[-1]['f0'] + segs[-1]['n']
    rowsout = []
    def add(kind, f_in, f_out, block, src='', src_in='', note=''):
        rowsout.append((f_in, {'block': 0, 'title': 1, 'card': 1, 'black': 1, 'cut': 2, 'hit': 3, 'line': 4}[kind],
                        [kind, tc(f_in / FPS), tc(f_out / FPS), f_in, f_out, f'{f_in / FPS:.3f}', f'{f_out / FPS:.3f}',
                         block, src, src_in, note]))
    prev_block = None
    for i, s in enumerate(segs):
        f_in, f_out = s['f0'], s['f0'] + s['n']
        if s['block'] != prev_block:
            b_end = max(t['f0'] + t['n'] for t in segs if t['block'] == s['block'])
            add('block', f_in, b_end, s['block'])
            prev_block = s['block']
        elif s['src'] not in ('CARD', 'BLACK'):
            add('cut', f_in, f_out, s['block'], os.path.basename(s['src']), f"{s['a']:.4f}")
        if s['src'] == 'CARD':
            kind = 'title' if s['card'].lstrip('+~0123456789.').startswith('^') else 'card'
            add(kind, f_in, f_out, s['block'], 'CARD', '', s['card'])
        elif s['src'] == 'BLACK':
            add('black', f_in, f_out, s['block'], 'BLACK')
        for name, clip, t in HITS:
            if os.path.basename(s['src']) == clip:
                ff = first_frame(s['a'])
                k = int(round(t * FPS)) - ff
                if 0 <= k / s['sp'] < s['n']:
                    fh = f_in + int(round(k / s['sp']))
                    add('hit', fh, fh, s['block'], clip, f'{t:.4f}', name)
    if speech:
        for t0, t1, pk in detect_lines(speech):
            f_in, f_out = int(round(t0 * FPS)), int(round(t1 * FPS))
            s = next((x for x in segs if x['f0'] <= f_in < x['f0'] + x['n']), segs[-1])
            clip, st = audio_source(s, t0)
            add('line', f_in, f_out, s['block'], clip, f'{st:.3f}', f'{pk:.1f} dBFS')
    rowsout.sort(key=lambda r: (r[0], r[1]))
    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    with open(out, 'w') as fo:
        fo.write(f'# spotting sheet for {cut_id}: {total} frames = {tc(total / FPS)} at {FPS} fps. '
                 f'Generated by bin/tool spotting from {edl}' + (f' and {os.path.basename(speech)}' if speech else '') + '. Do not edit by hand.\n')
        fo.write('kind\ttc_in\ttc_out\tframe_in\tframe_out\tsec_in\tsec_out\tblock\tsource\tsrc_in\tnote\n')
        for _, _, r in rowsout:
            fo.write('\t'.join(str(v) for v in r) + '\n')
    kinds = {}
    for _, _, r in rowsout: kinds[r[0]] = kinds.get(r[0], 0) + 1
    print(os.path.relpath(out, R.text), tc(total / FPS), kinds)
    return 0

if __name__ == '__main__':
    sys.exit(main())
